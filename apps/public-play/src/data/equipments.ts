export function getEquipmentById(id: string): EquipmentDef | undefined {
  return EQUIPMENTS.find((e) => e.id === id)
}

/** 精煉到下一級所需銀兩（+0→+1 … +14→+15） */
export function refineCostForLevel(
  baseRefineCost: number,
  currentLevel: number,
): number {
  const next = currentLevel + 1
  if (next > 15) return Infinity
  return Math.floor(baseRefineCost * next * (1 + Math.floor(currentLevel / 3)))
}

/** 精煉等級提供的額外攻防（簡化曲線） */
export function refineBonus(level: number): { attack: number; defense: number } {
  return {
    attack: Math.floor(level * 0.7),
    defense: Math.floor(level * 0.5),
  }
}

export function createOwnedEquipment(
  defId: string,
  uid: string,
): { uid: string; defId: string; refineLevel: number; quenched: boolean; poisoned: boolean } {
  return {
    uid,
    defId,
    refineLevel: 0,
    quenched: false,
    poisoned: false,
  }
}
