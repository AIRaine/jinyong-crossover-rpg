export function getTechNodeById(id: string): TechNodeDef | undefined {
  return TECH_NODES.find((n) => n.id === id)
}

export function getTechNodesByBranch(
  branch: TechNodeDef['branch'],
): TechNodeDef[] {
  return TECH_NODES.filter((n) => n.branch === branch).sort(
    (a, b) => a.tier - b.tier,
  )
}
