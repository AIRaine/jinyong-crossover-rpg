export function resolveOriginCategoryId(id: string | null | undefined): string | null {
  if (!id) return null
  if (ORIGINS.some((o) => o.id === id)) return id
  return LEGACY_ORIGIN_TO_CATEGORY[id] ?? null
}

export function getOriginById(id: string): OriginDef | undefined {
  const resolved = resolveOriginCategoryId(id)
  if (!resolved) return undefined
  return ORIGINS.find((o) => o.id === resolved)
}

/** 狀態列／敘事用：自填職稱優先，否則大類預設名 */
export function getOriginDisplayName(params: {
  originId: string | null
  originJobTitle?: string
}): string {
  const cat = params.originId ? getOriginById(params.originId) : undefined
  const custom = params.originJobTitle?.trim()
  if (custom) return custom
  return cat?.defaultJobTitle ?? cat?.name ?? '穿越客'
}

